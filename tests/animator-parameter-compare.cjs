'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../vrchat-animator-check/index.html'),'utf8');
const fn=html.match(/function compareParameterNames\(definedText,usedText\) \{[\s\S]*?\n\}/);
assert.ok(fn,'local comparison function must exist');
const compare=vm.runInNewContext('('+fn[0]+')');
const own=a=>Array.from(a);
let c=compare('IsDressed\nFaceMode\nIsDressed\n \n','IsDressed\nMisspelled\n');
assert.deepEqual(own(c.defined),['IsDressed','FaceMode']);
assert.deepEqual(own(c.used),['IsDressed','Misspelled']);
assert.deepEqual(own(c.missingFromDefined),['Misspelled']);
assert.deepEqual(own(c.notInCheckedConditions),['FaceMode']);
c=compare('Toggle\n','toggle\n');
assert.deepEqual(own(c.missingFromDefined),['toggle'],'parameter names are case-sensitive');
c=compare('  ABC  \r\nDEF\r\n',' ABC \nDEF\n');
assert.deepEqual(own(c.missingFromDefined),[],'trim CRLF and spaces');
c=compare('', 'AnyState\n');
assert.equal(c.defined.length,0,'empty input must not become a named parameter');
assert.match(html,/id="parameter-compare"/);
assert.match(html,/id="parameter-compare-button"/);
assert.match(html,/id="parameter-result" role="status" aria-live="polite" hidden/);
assert.match(html,/if\(names\.defined\.length>100\|\|names\.used\.length>100\)/);
assert.match(html,/入力文字列はこの端末のブラウザ内で照合するだけ/);
assert.match(html,/「未参照候補」を理由にParameterを削除しないでください/);
const section=html.split('id="parameter-compare"')[1].split('</section>')[0];
assert.doesNotMatch(section, /https:\/\/nokino-tools\.booth\.pm\/items\/\d+/,'comparison tool itself does not add an untracked outbound CTA');
console.log(JSON.stringify({status:'passed',checks:13,scope:'pure JS comparison function + static DOM and privacy assertions; no real-browser/GA4 or Unity test'}));
